static void controlLoop(void)
{
    switch (g_debug_.mode_) {

    case DEBUG_MODE_CHASSIS:
        debugRunChassis(&chassis_);
        break;

    case DEBUG_MODE_CAN:
        debugRunCanDirect();
        break;

    case DEBUG_MODE_NONE:
        if (rc_update) {
            if (!rcDataIsError()) {
                chassisSetTarget(&chassis_,
                    (float)remote_control.ch4_,
                    (float)remote_control.ch3_,
                    (float)remote_control.ch1_);
            }
            rc_update = 0;
        }
        chassisUpdate(&chassis_);
        chassisSendCmd(&chassis_);
        gimbalUpdate();
        gimbalSendCmd();
        break;
    }
}
